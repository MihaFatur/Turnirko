-- ============================================================================
-- Turnirko: dodatni dostop organizatorjev do tekmovanj (V62, nov 2026)
-- Samo PostgreSQL (mapa sqlite/ je zamrznjena).
--
-- Admin organizatorju odobri dostop do turnirja ali lige, ki je ni ustvaril
-- in ki ni od njegovega kluba, in pri vsaki dodelitvi odloci, ali tekmovanje
-- steje v mejo njegovega paketa. Vrstica je lahko tudi o LASTNIKU, ki je
-- tekmovanje ustvaril: tedaj samo spremeni, ali steje (privzeto steje) -
-- lastnistvo samo (turnir.id_ustvaril) se ne spremeni.
--
-- dodeljen_ob je cas, od katerega vrstica steje v mejo (sezona se zacne
-- 1. julija): za tekmovanje, ki ga je organizator ustvaril, steje cas
-- nastanka tekmovanja, za dodeljeno pa trenutek dodelitve.
-- ============================================================================

CREATE TABLE dostop_organizatorja (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_turnir      bigint REFERENCES turnir (id) ON DELETE CASCADE,
    id_liga        bigint REFERENCES liga (id) ON DELETE CASCADE,
    id_racun       bigint NOT NULL REFERENCES uporabnik (id) ON DELETE CASCADE,
    steje_v_mejo   boolean NOT NULL,
    dodeljen_ob    timestamp(3) NOT NULL,
    CHECK ((id_turnir IS NULL) <> (id_liga IS NULL))
);

CREATE UNIQUE INDEX idx_dostop_organizatorja_turnir ON dostop_organizatorja (id_turnir, id_racun)
    WHERE id_turnir IS NOT NULL;
CREATE UNIQUE INDEX idx_dostop_organizatorja_liga ON dostop_organizatorja (id_liga, id_racun)
    WHERE id_liga IS NOT NULL;
-- profil in meja paketa iscejo po racunu
CREATE INDEX idx_dostop_organizatorja_racun ON dostop_organizatorja (id_racun);
