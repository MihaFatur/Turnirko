-- ============================================================================
-- Turnirko: merjenje branja sodniskih listkov (V69, nov 2026)
-- Samo PostgreSQL (mapa sqlite/ je zamrznjena). Nacrt: docs/NACRT-BRANJE-LISTKOV.md, F1.
--
-- Brez meritev ne vemo, ali branje deluje. Ta migracija doda:
--
-- 1. Sled pregleda na branju (zapise jo potrditev):
--      pripravljen        ali je bil predlog primeren za potrditev z enim dotikom
--                         (brez opozoril in negotovih celic); null = branje pred V69
--      cas_pregleda_ms    koliko casa je organizator porabil za listek (meri vmesnik;
--                         nesmiselna vrednost se ne zapise)
--      nacin_potrditve    EN_DOTIK (gumb v vrsti) ali OBRAZEC (okno s fotografijo)
--
-- 2. Nakljucno kontrolo (kontrola): pripravljen predlog z majhno verjetnostjo
--    (privzeto 5 %) ni ponujen za en dotik, organizator ga pregleda v celoti. Ker
--    je kontrola izbrana nakljucno, iz njenih popravkov ocenimo, kako pogosto
--    »zanesljiv« predlog vsebuje napako, ki je nihce ne bi opazil.
--
-- 3. Zlati nabor (zlati_listek): po potrditvi se shrani poravnan listek (10 px/mm,
--    sivine, PNG), na katerem so ohranjeni SAMO piksli znotraj celic s tockami;
--    vse ostalo (imena, glava, noga) je belo. Zraven: lega celic, potrjen izid v
--    stolpcih listka in razlicica mreze, ki je brala. Imen ne vsebuje, zato se
--    hrani brez roka; najvec 5000 listkov, nakljucen vzorec vseh potrjenih
--    (vsak dobi nakljucen kljuc, ostane 5000 z najmanjsim). Na njem se meri
--    vsaka sprememba bralnika in vsaka nova mreza.
-- ============================================================================

ALTER TABLE branje_listka
    ADD COLUMN kontrola boolean NOT NULL DEFAULT false,
    ADD COLUMN pripravljen boolean,
    ADD COLUMN cas_pregleda_ms integer CHECK (cas_pregleda_ms BETWEEN 0 AND 3600000),
    ADD COLUMN nacin_potrditve text CHECK (nacin_potrditve IN ('EN_DOTIK', 'OBRAZEC'));

-- Meritev bere branja po casu nastanka (obdobje) tudi brez turnirja.
CREATE INDEX idx_branje_listka_ustvarjeno ON branje_listka (ustvarjeno_ob);

CREATE TABLE zlati_listek (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_branje      bigint UNIQUE REFERENCES branje_listka (id) ON DELETE SET NULL,
    slika          bytea NOT NULL,
    celice         text NOT NULL,
    resnica        text NOT NULL,
    stevilo_nizov  smallint NOT NULL CHECK (stevilo_nizov BETWEEN 1 AND 9),
    model          text,
    kljuc          double precision NOT NULL CHECK (kljuc >= 0 AND kljuc < 1),
    ustvarjeno_ob  timestamp(3) NOT NULL
);
CREATE INDEX idx_zlati_listek_kljuc ON zlati_listek (kljuc);
