-- ============================================================================
-- Turnirko: branje sodniskih listkov s fotografije (V68, nov 2026)
-- Samo PostgreSQL (mapa sqlite/ je zamrznjena).
--
-- Organizator na turnirju s telefonom fotografira izpolnjen listek. Streznik
-- prebere QR kodo tekme, po oznakah v vogalih listka poravna fotografijo,
-- izreze celice in rocno napisane tocke prebere z LASTNO nevronsko mrezo
-- (brez zunanjih storitev in brez cene na listek). Iz tega sestavi PREDLOG
-- izida; v tekmo se izid zapise sele, ko ga organizator potrdi - po isti poti
-- in z istimi preverbami kot rocni vnos. Vrstica branja je zato samo predlog
-- in njegova sled:
--   stanje       V_VRSTI (caka na branje), PREBRANO (predlog caka na potrditev),
--                NAPAKA (branje ni uspelo), POTRJENO, ZAVRZENO
--   prepoznava   kako je bila tekma najdena: KODA (QR ali natisnjena stevilka),
--                IMENA (prebrana imena, ujemanje s tekmami turnirja), ROCNO
--                (izbral organizator)
--   prebrano     JSON prepisa (PrebranListek), za merjenje in izboljsave
--   potrjeno     JSON potrjenega izida; z njim in s »prebrano« se meri, koliko
--                listkov je bilo prebranih brez popravka (popravljeno)
--   model        razlicica mreze stevk, ki je brala
--
-- Fotografija je v svoji tabeli, da seznam branj nikoli ne nalaga slik. Ostane
-- 30 dni po turnirju (dokaz ob pritozbi), potem jo nocno opravilo izbrise in
-- zapise slika_izbrisana_ob; vrstica branja ostane kot merilo natancnosti.
--
-- Ucenje (stevka_listka, mreza_stevk): ob potrditvi se iz fotografije izrezejo
-- stevke s pravo vrednostjo (samo okenca s stevilkami, brez imen). Na njih se
-- mreza nocno dotrenira; nova razlicica se sprejme samo, ce na preizkusnih
-- stevkah bere bolje od prejsnje. Prva razlicica je vgrajena v aplikacijo
-- (resources/branje/stevke.bin) in tu nima vrstice.
-- ============================================================================

CREATE TABLE branje_listka (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_turnir           bigint NOT NULL REFERENCES turnir (id) ON DELETE CASCADE,
    id_tekma            bigint REFERENCES tekma (id) ON DELETE SET NULL,
    stanje              text NOT NULL
                        CHECK (stanje IN ('V_VRSTI', 'PREBRANO', 'NAPAKA', 'POTRJENO', 'ZAVRZENO')),
    prepoznava          text CHECK (prepoznava IN ('KODA', 'IMENA', 'ROCNO')),
    prebrano            text,
    potrjeno            text,
    popravljeno         boolean,
    napaka              text,
    model               text,
    id_nalozil          bigint REFERENCES uporabnik (id) ON DELETE SET NULL,
    ustvarjeno_ob       timestamp(3) NOT NULL,
    prebrano_ob         timestamp(3),
    zakljuceno_ob       timestamp(3),
    slika_izbrisana_ob  timestamp(3)
);
CREATE INDEX idx_branje_listka_turnir ON branje_listka (id_turnir, ustvarjeno_ob);
CREATE INDEX idx_branje_listka_tekma ON branje_listka (id_tekma);
CREATE INDEX idx_branje_listka_nalozil ON branje_listka (id_nalozil, ustvarjeno_ob);

CREATE TABLE branje_listka_slika (
    id_branje  bigint PRIMARY KEY REFERENCES branje_listka (id) ON DELETE CASCADE,
    vsebina    bytea NOT NULL,
    sirina     integer NOT NULL CHECK (sirina > 0),
    visina     integer NOT NULL CHECK (visina > 0)
);

-- Stevka potrjenega listka: 28 x 28 sivin (0-255, tako kot MNIST) in vrednost,
-- ki jo je potrdil organizator; mreza_prav = ali jo je mreza ob branju prebrala prav.
CREATE TABLE stevka_listka (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_branje      bigint REFERENCES branje_listka (id) ON DELETE SET NULL,
    slika          bytea NOT NULL CHECK (length(slika) = 784),
    vrednost       smallint NOT NULL CHECK (vrednost BETWEEN 0 AND 9),
    mreza_prav     boolean NOT NULL,
    ustvarjeno_ob  timestamp(3) NOT NULL
);
CREATE INDEX idx_stevka_listka_ustvarjeno ON stevka_listka (ustvarjeno_ob);

-- Razlicice mreze stevk iz nocnega ucenja. V uporabi je zadnja sprejeta.
CREATE TABLE mreza_stevk (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utezi            bytea NOT NULL,
    vzorcev          integer NOT NULL CHECK (vzorcev >= 0),
    natancnost_prej  real NOT NULL,
    natancnost       real NOT NULL,
    sprejeta         boolean NOT NULL,
    ustvarjeno_ob    timestamp(3) NOT NULL
);
