-- ============================================================================
-- Izhodisce sheme za PostgreSQL (prenova baze, okt 2026; docs/PRENOVA-BAZE.md)
--
-- Shema je ENAKA stanju SQLite po V53 (db/migration/sqlite), le s pravimi
-- tipi. Stevilka 53 je namerna: zgodovina migracij ostane berljiva (»V41 je
-- uvedla kvalifikacije« velja se naprej), prva nova migracija je V54. Prazna
-- baza PostgreSQL izvede samo to datoteko; komentarji z oznako (V..) povedo,
-- katera migracija SQLite je stolpec ali pravilo uvedla.
--
-- Preslikava tipov (stolpci so v istem vrstnem redu kot v SQLite):
--   id INTEGER PRIMARY KEY      -> bigint GENERATED BY DEFAULT AS IDENTITY
--   tuji kljuci, verzija        -> bigint (v entitetah Long / long)
--   INTEGER CHECK (x IN (0, 1)) -> boolean (CHECK odpade)
--   ostali INTEGER              -> integer
--   besedilo z datumom          -> date
--   besedilo s casom            -> timestamp(3) brez casovnega pasu
--                                  (aplikacija dela z LocalDateTime)
--   REAL                        -> double precision (rating se mora ujemati
--                                  do zadnjega bita)
--
-- Baza mora biti ustvarjena z razvrscanjem po kodnih tockah (C.UTF-8), kot ga
-- je imel SQLite; slovenski vrstni red ureja Java (SlovenskaAbeceda).
-- ============================================================================

CREATE TABLE kraj (
    postna_st   integer PRIMARY KEY,
    ime         text NOT NULL CHECK (length(ime) BETWEEN 2 AND 40)
);

CREATE TABLE klub (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ime         text NOT NULL CHECK (length(ime) BETWEEN 2 AND 50),
    -- kratko ime za izpise, npr. "NTK SAV"
    kratica     text CHECK (kratica IS NULL OR length(kratica) BETWEEN 2 AND 10)
);

CREATE TABLE igralec (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ime                 text NOT NULL CHECK (length(trim(ime)) BETWEEN 2 AND 30),
    priimek             text NOT NULL CHECK (length(trim(priimek)) BETWEEN 2 AND 40),
    -- spol je obvezen, ker dolocajo kategorije dogodkov (moski/zenske)
    spol                text NOT NULL CHECK (spol IN ('MOSKI', 'ZENSKI')),
    -- neznan datum je 1. 1. 1900 (uvoz brez datuma)
    datum_rojstva       date NOT NULL CHECK (datum_rojstva >= '1900-01-01'),
    email               text UNIQUE CHECK (email IS NULL OR email LIKE '%_@_%._%'),
    telefonska_st       text UNIQUE,
    igralna_roka        text CHECK (igralna_roka IS NULL OR igralna_roka IN ('LEVA', 'DESNA')),
    -- registrska stevilka pri NTZS (ce jo igralec ima)
    ntzs_licenca        text UNIQUE,
    drzavljanstvo       text NOT NULL DEFAULT 'SLO',
    naslov              text,
    postna_st           integer REFERENCES kraj (postna_st),
    id_klub             bigint REFERENCES klub (id),
    -- mehko brisanje: arhiviran igralec se ne pojavlja v seznamih za prijavo
    arhiviran           boolean NOT NULL DEFAULT false,
    ustvarjen_ob        timestamp(3) NOT NULL,
    posodobljen_ob      timestamp(3),
    -- zacetni rating 800 namesto starostnega sidra (V36)
    rekreativni_vstop   boolean NOT NULL DEFAULT false
);
CREATE INDEX idx_igralec_priimek_ime ON igralec (priimek, ime);

CREATE TABLE uporabnik (
    id                          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uporabnisko_ime             text NOT NULL UNIQUE CHECK (length(trim(uporabnisko_ime)) BETWEEN 3 AND 120),
    -- BCrypt zgostitev gesla (nikoli cistopis)
    geslo_hash                  text NOT NULL,
    vloga                       text NOT NULL CHECK (vloga IN ('ADMIN', 'ORGANIZATOR', 'IGRALEC')),
    status                      text NOT NULL DEFAULT 'POTRJEN' CHECK (status IN ('CAKA', 'POTRJEN', 'ZAVRNJEN')),
    -- povezava na sifrant igralcev; en igralec ima lahko najvec en racun
    id_igralec                  bigint UNIQUE REFERENCES igralec (id),
    -- klub, ki mu uporabnik pripada (za organizatorja; doloci ga admin ob potrditvi)
    id_klub                     bigint REFERENCES klub (id),
    -- kar je oseba navedla ob registraciji (podlaga adminu za potrditev)
    prijavljeno_ime             text,
    prijavljeni_priimek         text,
    id_klub_zelja               bigint REFERENCES klub (id),
    aktiven                     boolean NOT NULL DEFAULT true,
    ustvarjen_ob                timestamp(3) NOT NULL,
    -- potrjen naslov in soglasje skrbnika (V33)
    email_potrjen_ob            timestamp(3),
    prijavljeni_datum_rojstva   date,
    email_skrbnika              text,
    skrbnik_potrjen_ob          timestamp(3),
    vir_povezave                text CHECK (vir_povezave IS NULL OR vir_povezave IN ('ADMIN', 'SAMODEJNO')),
    povezan_ob                  timestamp(3),
    -- obvestila po kolu (V50)
    obvestila_po_kolu           boolean NOT NULL DEFAULT true,
    zeton_odjave                text,
    -- potrjen racun igralca mora biti povezan z igralcem, sicer ne ve, cigav je
    CHECK (vloga <> 'IGRALEC' OR status <> 'POTRJEN' OR id_igralec IS NOT NULL)
);
CREATE INDEX idx_uporabnik_status ON uporabnik (status);
CREATE INDEX idx_uporabnik_igralec ON uporabnik (id_igralec);
CREATE INDEX idx_uporabnik_klub ON uporabnik (id_klub);
CREATE UNIQUE INDEX idx_uporabnik_zeton_odjave ON uporabnik (zeton_odjave)
    WHERE zeton_odjave IS NOT NULL;

CREATE TABLE turnir (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ime                 text NOT NULL CHECK (length(trim(ime)) BETWEEN 3 AND 80),
    postna_st           integer REFERENCES kraj (postna_st),
    dvorana             text,
    datum_zacetka       date,
    datum_konca         date,
    -- status doloca streznik, nikoli odjemalec
    status              text NOT NULL CHECK (status IN ('PRIPRAVA', 'V_TEKU', 'ZAKLJUCEN')),
    opombe              text,
    verzija             bigint NOT NULL DEFAULT 0,
    ustvarjen_ob        timestamp(3) NOT NULL,
    -- lastnistvo (V6): racun, ki je turnir ustvaril, in posnetek njegovega kluba
    id_ustvaril         bigint REFERENCES uporabnik (id),
    id_klub_lastnik     bigint REFERENCES klub (id),
    -- raven tekmovanja (V20) in vir uvoza (V27)
    raven               text NOT NULL DEFAULT 'KLUBSKO'
                            CHECK (raven IN ('URADNO', 'KLUBSKO', 'REKREATIVNO', 'NE_STEJE')),
    vir                 text CHECK (vir IS NULL OR vir IN ('STUPA', 'STARA_NTZS')),
    -- razdelki zavihka Zanimivosti, ki jih gost ne vidi (V51)
    skrite_zanimivosti  text,
    CHECK (datum_konca IS NULL OR datum_zacetka IS NULL OR datum_konca >= datum_zacetka)
);
CREATE INDEX idx_turnir_klub_lastnik ON turnir (id_klub_lastnik);

CREATE TABLE dogodek (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_turnir               bigint NOT NULL REFERENCES turnir (id),
    -- npr. "Clani posamicno", "Clani dvojice", "U15 ekipno"
    ime                     text NOT NULL CHECK (length(trim(ime)) BETWEEN 3 AND 60),
    disciplina              text NOT NULL CHECK (disciplina IN ('POSAMICNO', 'DVOJICE', 'EKIPNO')),
    spol_kategorija         text NOT NULL CHECK (spol_kategorija IN ('MOSKI', 'ZENSKE', 'MESANO', 'KDORKOLI')),
    -- prosto besedilo, npr. 'U15', 'CLANI', 'VETERANI 40+'
    starostna_kategorija    text,
    sistem_tekmovanja       text NOT NULL CHECK (sistem_tekmovanja IN ('IZLOCILNI', 'SKUPINE_IZLOCILNI',
                                                                     'KROZNI', 'SKUPINE', 'SKUPINE_ZA_MESTA',
                                                                     'SV_REGIJA')),
    -- "najboljsi od N nizov" - privzeta vrednost za tekme tega dogodka (pri
    -- ekipnem dogodku za posamicne tekme srecanja)
    privzeto_stevilo_nizov  integer NOT NULL CHECK (privzeto_stevilo_nizov IN (3, 5, 7)),
    prijavnina              double precision CHECK (prijavnina IS NULL OR prijavnina >= 0),
    rok_prijave             date,
    status                  text NOT NULL CHECK (status IN ('PRIPRAVA', 'V_TEKU', 'ZAKLJUCEN')),
    -- Nastavitvi skupinskega dela. Pri sistemu SKUPINE obvezni (format TOP),
    -- pri SKUPINE_ZA_MESTA je stevilo skupin neobvezno (brez njega ga doloci zreb),
    -- pri SV_REGIJA sta to skupine na poln nivo in igralci v skupini (privzeto 4 in 4).
    -- Zgornja meja 26 je posledica oznak skupin A..Z.
    stevilo_skupin          integer CHECK (stevilo_skupin IS NULL OR stevilo_skupin BETWEEN 1 AND 26),
    velikost_skupine        integer CHECK (velikost_skupine IS NULL OR velikost_skupine BETWEEN 2 AND 24),
    -- sistem SV_REGIJA: stevilo nivojev in rocna razdelitev po nivojih
    stevilo_nivojev         integer CHECK (stevilo_nivojev IS NULL OR stevilo_nivojev BETWEEN 1 AND 9),
    velikosti_nivojev       text CHECK (velikosti_nivojev IS NULL OR length(velikosti_nivojev) <= 80),
    rangov_v_zreb           text CHECK (rangov_v_zreb IS NULL OR length(rangov_v_zreb) <= 40),
    -- ekipni dogodek: format srecanja, prag zmag za srecanje (NULL = vse tekme)
    format_srecanja         text CHECK (format_srecanja IS NULL OR format_srecanja IN
                                        ('SNTL', 'CORBILLON', 'SAVINJA', 'SNTL_PRVA',
                                         'SNTL_BREZ_DVOJIC', 'OLIMPIJSKI',
                                         'SNTL_DVOJICE_SEDMA', 'SNTL_PRVA_DVOJICE_CETRTA',
                                         'EKIPNI_DP', 'POKAL_NTZS', 'DSI')),
    zmag_za_srecanje        integer CHECK (zmag_za_srecanje IS NULL OR zmag_za_srecanje >= 1),
    -- izlocilna mreza s tekmo za 3. mesto (porazenca polfinala)
    tekma_za_tretje_mesto   boolean NOT NULL DEFAULT false,
    verzija                 bigint NOT NULL DEFAULT 0,
    ustvarjen_ob            timestamp(3) NOT NULL,
    CHECK (sistem_tekmovanja <> 'SKUPINE'
           OR (stevilo_skupin IS NOT NULL AND velikost_skupine IS NOT NULL)),
    -- dvojice igrajo izkljucno izlocilno mrezo: krozni sistem in skupine bi
    -- za pare potrebovala se lestvice parov, ki jih ni
    CHECK (disciplina <> 'DVOJICE' OR sistem_tekmovanja = 'IZLOCILNI'),
    -- "strogo mesano" je lastnost PARA, zato pri posamicnem in ekipnem dogodku
    -- ni izbira; tam je odprta kategorija KDORKOLI
    CHECK (spol_kategorija <> 'MESANO' OR disciplina = 'DVOJICE'),
    -- ekipni dogodek brez formata ne ve, kako se igra srecanje; drugi dogodki
    -- srecanj nimajo
    CHECK ((disciplina = 'EKIPNO') = (format_srecanja IS NOT NULL)),
    CHECK (zmag_za_srecanje IS NULL OR disciplina = 'EKIPNO'),
    -- tekma za 3. mesto je del izlocilne mreze
    CHECK (NOT tekma_za_tretje_mesto OR sistem_tekmovanja IN ('IZLOCILNI', 'SKUPINE_IZLOCILNI')),
    -- nivoji so lastnost sistema SV_REGIJA
    CHECK ((stevilo_nivojev IS NULL AND velikosti_nivojev IS NULL AND rangov_v_zreb IS NULL)
           OR sistem_tekmovanja = 'SV_REGIJA')
);
CREATE INDEX idx_dogodek_turnir ON dogodek (id_turnir);

CREATE TABLE liga (
    id                              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ime                             text NOT NULL CHECK (length(trim(ime)) BETWEEN 3 AND 80),
    -- npr. "2025/26"
    sezona                          text CHECK (sezona IS NULL OR length(sezona) BETWEEN 2 AND 20),
    spol_kategorija                 text NOT NULL CHECK (spol_kategorija IN ('MOSKI', 'ZENSKE', 'MESANO')),
    -- format srecanja doloca stevilo igralcev, dvojice in vrstni red tekem
    format_srecanja                 text NOT NULL CHECK (format_srecanja IN
                                        ('SNTL', 'CORBILLON', 'SAVINJA', 'SNTL_PRVA',
                                         'SNTL_BREZ_DVOJIC', 'OLIMPIJSKI',
                                         'SNTL_DVOJICE_SEDMA', 'SNTL_PRVA_DVOJICE_CETRTA',
                                         'DSI')),
    -- "najboljsi od N nizov" za posamicne tekme lige
    stevilo_nizov                   integer NOT NULL CHECK (stevilo_nizov IN (3, 5, 7)),
    -- prvi do N dobljenih tekem konca srecanje; NULL = odigrajo se vse tekme
    zmag_za_srecanje                integer CHECK (zmag_za_srecanje IS NULL OR zmag_za_srecanje >= 1),
    -- dvokrozno (doma in v gosteh) ali enokrozno
    dvokrozno                       boolean NOT NULL DEFAULT true,
    tocke_zmaga                     integer NOT NULL DEFAULT 2 CHECK (tocke_zmaga >= 0),
    tocke_neodloceno                integer NOT NULL DEFAULT 1 CHECK (tocke_neodloceno >= 0),
    tocke_poraz                     integer NOT NULL DEFAULT 0 CHECK (tocke_poraz >= 0),
    dovoljeno_neodloceno            boolean NOT NULL DEFAULT true,
    -- prepoved dvojne registracije: igralec sme biti v kadru le ene ekipe v ligi
    prepoved_dvojne_registracije    boolean NOT NULL DEFAULT false,
    -- povezava na visjo ligo (za prehode ob koncu sezone); NULL = najvisja
    id_visja_liga                   bigint REFERENCES liga (id),
    -- koliko ekip napreduje v visjo / izpade v nizjo ligo
    st_napreduje                    integer NOT NULL DEFAULT 0 CHECK (st_napreduje >= 0),
    st_izpade                       integer NOT NULL DEFAULT 0 CHECK (st_izpade >= 0),
    status                          text NOT NULL CHECK (status IN ('PRIPRAVA', 'V_TEKU', 'ZAKLJUCEN')),
    -- predloga uradnega ekipnega zapisnika za natis (V7)
    predloga_listka                 text NOT NULL DEFAULT 'SNTL_23' CHECK (predloga_listka IN ('SNTL_1', 'SNTL_23')),
    -- seme terminov kol (V10)
    zacetek_prvega_kola             timestamp(3),
    razmik_dni                      integer CHECK (razmik_dni IS NULL OR razmik_dni BETWEEN 1 AND 365),
    -- lastnistvo (V6): racun, ki je ligo ustvaril, in posnetek njegovega kluba
    id_ustvaril                     bigint REFERENCES uporabnik (id),
    id_klub_lastnik                 bigint REFERENCES klub (id),
    verzija                         bigint NOT NULL DEFAULT 0,
    ustvarjen_ob                    timestamp(3) NOT NULL,
    -- enakomerna razvrstitev (V16), lige na domaci strani (V17)
    enakomerna_razvrstitev          boolean NOT NULL DEFAULT false,
    na_domaci                       boolean NOT NULL DEFAULT false,
    -- raven tekmovanja (V20)
    raven                           text NOT NULL DEFAULT 'KLUBSKO'
                                        CHECK (raven IN ('URADNO', 'KLUBSKO', 'REKREATIVNO', 'NE_STEJE')),
    -- rocni razpored (V26), vir uvoza (V27)
    rocni_zreb                      boolean NOT NULL DEFAULT false,
    vir                             text CHECK (vir IS NULL OR vir IN ('STUPA', 'STARA_NTZS')),
    -- koncnica (V28), odbitek za poraz brez borbe (V29), ure kola (V31)
    koncnica_ekip                   integer CHECK (koncnica_ekip IS NULL OR koncnica_ekip IN (2, 4, 8)),
    koncnica_zmag                   integer,
    odbitek_brez_boja               integer NOT NULL DEFAULT 0 CHECK (odbitek_brez_boja BETWEEN 0 AND 5),
    ure_srecanj                     text,
    -- kvalifikacije med ligami (V41)
    st_kvalifikacije_gor            integer NOT NULL DEFAULT 0 CHECK (st_kvalifikacije_gor >= 0),
    st_kvalifikacije_dol            integer NOT NULL DEFAULT 0 CHECK (st_kvalifikacije_dol >= 0),
    id_kvalifikacije_visja          bigint REFERENCES liga (id),
    id_kvalifikacije_nizja          bigint REFERENCES liga (id),
    -- skriti razdelki Zanimivosti (V51), opombe lige (V52)
    skrite_zanimivosti              text,
    opombe                          text,
    CHECK ((koncnica_zmag IS NULL AND koncnica_ekip IS NULL)
           OR (koncnica_zmag BETWEEN 1 AND 4 AND koncnica_ekip IS NOT NULL)),
    CHECK ((id_kvalifikacije_nizja IS NULL) = (id_kvalifikacije_visja IS NULL)
           AND (id_kvalifikacije_nizja IS NULL OR id_kvalifikacije_nizja <> id_kvalifikacije_visja)),
    -- liga ne more biti sama sebi nadrejena (daljsih krogov baza ne vidi -
    -- te prepreci LigaStoritev.nastaviPrehode)
    CHECK (id_visja_liga IS NULL OR id_visja_liga <> id)
);
CREATE INDEX idx_liga_klub_lastnik ON liga (id_klub_lastnik);
CREATE INDEX idx_liga_visja ON liga (id_visja_liga);
CREATE INDEX idx_liga_kvalifikacije ON liga (id_kvalifikacije_visja, id_kvalifikacije_nizja);

CREATE TABLE ekipa (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_liga         bigint REFERENCES liga (id),
    id_dogodek      bigint REFERENCES dogodek (id),
    -- NEOBVEZEN: prazen pomeni prosto ekipo, ki nastopa samo v tem tekmovanju
    id_klub         bigint REFERENCES klub (id),
    -- zaporedna ekipa kluba v tekmovanju (1 = prva mostvo, npr. "Savinja 1");
    -- prosta ekipa je vedno 1, ker je nima s cim steti
    zaporedna       integer NOT NULL DEFAULT 1 CHECK (zaporedna >= 1),
    -- prikazano ime; pri klubski ekipi neobvezno (sestavi se iz kluba in
    -- zaporedne), pri prosti obvezno
    ime             text CHECK (ime IS NULL OR length(trim(ime)) BETWEEN 2 AND 60),
    verzija         bigint NOT NULL DEFAULT 0,
    st_nosilca      integer CHECK (st_nosilca IS NULL OR st_nosilca >= 1),
    UNIQUE (id_liga, id_klub, zaporedna),
    -- ekipa brez kluba brez imena ne bi imela nobenega poimenovanja
    CHECK (id_klub IS NOT NULL OR ime IS NOT NULL),
    -- ekipa nastopa v natanko enem tekmovanju
    CHECK ((id_liga IS NULL) <> (id_dogodek IS NULL))
);
CREATE INDEX idx_ekipa_liga ON ekipa (id_liga);
CREATE INDEX idx_ekipa_dogodek ON ekipa (id_dogodek);
CREATE UNIQUE INDEX idx_ekipa_prosta_ime ON ekipa (id_liga, ime) WHERE id_klub IS NULL;
CREATE UNIQUE INDEX idx_ekipa_dogodek_klub ON ekipa (id_dogodek, id_klub, zaporedna)
    WHERE id_dogodek IS NOT NULL AND id_klub IS NOT NULL;
CREATE UNIQUE INDEX idx_ekipa_dogodek_prosta_ime ON ekipa (id_dogodek, ime)
    WHERE id_dogodek IS NOT NULL AND id_klub IS NULL;

CREATE TABLE skupina (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_dogodek  bigint NOT NULL REFERENCES dogodek (id),
    -- oznaka skupine: 'A', 'B', 'C'...
    oznaka      text NOT NULL CHECK (length(oznaka) BETWEEN 1 AND 3),
    -- skupine za mesta (V28): stopnja, ime in prvo mesto, ki ga skupina odloca
    stopnja     integer NOT NULL DEFAULT 1 CHECK (stopnja >= 1),
    ime         text CHECK (ime IS NULL OR length(trim(ime)) BETWEEN 1 AND 40),
    prvo_mesto  integer CHECK (prvo_mesto IS NULL OR prvo_mesto >= 1),
    -- nivo sistema SV_REGIJA (V42)
    nivo        integer NOT NULL DEFAULT 1 CHECK (nivo >= 1),
    UNIQUE (id_dogodek, oznaka)
);

CREATE TABLE prijava (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_dogodek              bigint NOT NULL REFERENCES dogodek (id),
    -- posamicna prijava oz. prvi igralec para; pri ekipnem dogodku prazen
    id_igralec              bigint REFERENCES igralec (id),
    -- drugi igralec para (samo pri disciplini DVOJICE)
    id_igralec_2            bigint REFERENCES igralec (id),
    -- ekipa (samo pri disciplini EKIPNO); igralce nosi njen kader
    id_ekipa                bigint REFERENCES ekipa (id),
    -- klub, za katerega je igralec (ekipa) nastopal OB PRIJAVI (posnetek)
    id_klub_ob_prijavi      bigint REFERENCES klub (id),
    id_klub_ob_prijavi_2    bigint REFERENCES klub (id),
    status                  text NOT NULL CHECK (status IN ('PRIJAVLJEN', 'ODJAVLJEN', 'DISKVALIFICIRAN', 'REZERVA', 'ODSTOPIL')),
    -- Mesto na jakostni lestvici dogodka (1 = najmocnejsi). Pri sistemu
    -- SKUPINE po njem tece izbor najboljsih N in razporeditev v skupine,
    -- zato ga administrator lahko rocno uredi pred zrebom.
    st_nosilca              integer CHECK (st_nosilca IS NULL OR st_nosilca >= 1),
    -- posnetek ratinga ob zrebu - za sledljivost in ponovljivost zreba
    rating_ob_zrebu         integer,
    rating_ob_zrebu_2       integer,
    id_skupina              bigint REFERENCES skupina (id),
    mesto_v_skupini         integer,
    -- koncna uvrstitev na dogodku (1 = zmagovalec); od nje bodo odvisne tocke
    koncno_mesto            integer CHECK (koncno_mesto IS NULL OR koncno_mesto >= 1),
    placano                 boolean NOT NULL DEFAULT false,
    prijavljen_ob           timestamp(3) NOT NULL,
    verzija                 bigint NOT NULL DEFAULT 0,
    UNIQUE (id_dogodek, id_igralec),
    -- igralec ne more biti sam svoj soigralec
    CHECK (id_igralec_2 IS NULL OR id_igralec_2 <> id_igralec),
    -- natanko ena tekmovalna enota: igralec (par) ali ekipa
    CHECK ((id_igralec IS NULL) <> (id_ekipa IS NULL)),
    CHECK (id_ekipa IS NULL OR id_igralec_2 IS NULL)
);
CREATE INDEX idx_prijava_dogodek ON prijava (id_dogodek);
CREATE UNIQUE INDEX idx_prijava_soigralec ON prijava (id_dogodek, id_igralec_2)
    WHERE id_igralec_2 IS NOT NULL;
CREATE UNIQUE INDEX idx_prijava_ekipa ON prijava (id_ekipa) WHERE id_ekipa IS NOT NULL;

-- zrebi za vsa mesta sistema SV_REGIJA (V42)
CREATE TABLE zreb (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_dogodek      bigint NOT NULL REFERENCES dogodek (id),
    nivo            integer NOT NULL CHECK (nivo >= 1),
    -- 0 = glavni, 1 = tolazilni, 2 = tretji ...
    indeks          integer NOT NULL CHECK (indeks >= 0),
    -- najvisje mesto na DOGODKU, ki ga odloca zmagovalec zreba
    prvo_mesto      integer NOT NULL CHECK (prvo_mesto >= 1),
    -- koliko igralcev pride v zreb iz skupin (mreza je potenca 2 nad tem)
    st_udelezencev  integer NOT NULL CHECK (st_udelezencev >= 1),
    -- tekme so zgrajene (zreb nastane, ko so odigrane vse skupine nivoja)
    zgrajen         boolean NOT NULL DEFAULT false,
    -- razpored mest je vpisal organizator in ni bil nakljucen
    rocni           boolean NOT NULL DEFAULT false,
    -- prijave po mestih v mrezi od vrha navzdol ("12,40,,7"), prazno = prosto
    -- mesto; iz tekem se razporeda ne da zanesljivo prebrati (prosti prehodi
    -- tekem ne ustvarijo), rocno urejanje pa mora izhajati iz trenutnega stanja
    razpored        text,
    verzija         bigint NOT NULL DEFAULT 0,
    UNIQUE (id_dogodek, nivo, indeks)
);
CREATE INDEX idx_zreb_dogodek ON zreb (id_dogodek);

CREATE TABLE tekma (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_dogodek              bigint NOT NULL REFERENCES dogodek (id),
    faza                    text NOT NULL CHECK (faza IN ('SKUPINA', 'GLAVNI', 'TOLAZILNI')),
    id_skupina              bigint REFERENCES skupina (id),
    kolo                    integer NOT NULL CHECK (kolo >= 1),
    pozicija                integer NOT NULL CHECK (pozicija >= 1),
    id_prijava_1            bigint REFERENCES prijava (id),
    id_prijava_2            bigint REFERENCES prijava (id),
