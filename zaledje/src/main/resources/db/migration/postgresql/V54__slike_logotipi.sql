-- Dvojnica db/migration/sqlite/V54__slike_logotipi.sql za PostgreSQL: iste
-- tabele in omejitve, s tipi izhodisca V53 (bigint identity, timestamp(3),
-- bytea namesto BLOB). Razlaga stolpcev je v SQLite razlicici.
-- ============================================================================

CREATE TABLE slika (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zgostitev      text NOT NULL UNIQUE CHECK (length(zgostitev) = 64),
    namen          text NOT NULL CHECK (namen IN ('LOGOTIP')),
    sirina         integer NOT NULL CHECK (sirina > 0),
    visina         integer NOT NULL CHECK (visina > 0),
    id_nalozil     bigint REFERENCES uporabnik (id) ON DELETE SET NULL,
    ustvarjena_ob  timestamp(3) NOT NULL
);

CREATE INDEX idx_slika_nalozil ON slika (id_nalozil);

CREATE TABLE slika_razlicica (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_slika   bigint NOT NULL REFERENCES slika (id) ON DELETE CASCADE,
    velikost   text NOT NULL CHECK (velikost IN ('TISK', 'ZASLON', 'DELJENJE')),
    vrsta      text NOT NULL CHECK (vrsta IN ('image/png', 'image/jpeg')),
    sirina     integer NOT NULL CHECK (sirina > 0),
    visina     integer NOT NULL CHECK (visina > 0),
    vsebina    bytea NOT NULL,
    UNIQUE (id_slika, velikost)
);

-- Logotip je prikaz, ne pravilo tekmovanja (glej SQLite razlicico).
ALTER TABLE liga ADD COLUMN id_logotip bigint REFERENCES slika (id);
ALTER TABLE turnir ADD COLUMN id_logotip bigint REFERENCES slika (id);
