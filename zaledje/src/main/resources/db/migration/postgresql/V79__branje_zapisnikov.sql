-- ============================================================================
-- Turnirko: branje ligaskih zapisnikov s fotografije (V79, 26. 11. 2026)
--
-- Organizator lige zapisnike kola natisne iz Turnirka (obliko »za bralnik«:
-- vrstice tekem ali tabela kadra), igralci na srecanju prekrizajo, kdo je igral
-- katero tekmo, in vpisejo tocke nizov. Organizator nato liste fotografira (ali
-- skenira v PDF) in Turnirko jih prebere z isto lastno mrezo stevk kot listke
-- turnirja. Zanesljivo prebran zapisnik se zapise sam (odlocitev lastnika),
-- ostale organizator pregleda in potrdi.
--
-- natis_zapisnika: ob tisku se zapise, kaj je na listu (srecanje, oblika,
-- razlicica postavitve, format, nizi in kadra po vrsticah), QR pa nosi samo id
-- natisa in skrivnost. Bralnik tako ve, katera vrstica je kateri igralec, tudi ce
-- se je kader po tisku spremenil. Enak natis se ne podvaja (iste vrednosti).
--
-- branje_zapisnika: sled branja kot pri branje_listka. stanje
--   V_VRSTI, PREBRANO (caka organizatorja), NAPAKA, ZAPISANO, ZAVRZENO.
-- samodejno = organizator je ob nalaganju dovolil samodejni zapis zanesljivih;
-- zapisano_samodejno = zapisan brez organizatorja. Fotografija je v svoji tabeli
-- in se izbrise po 30 dneh (kot listki), vrstica ostane.
--
-- stevka_listka dobi tretji vir: potrjen ligaski zapisnik.
-- ============================================================================

CREATE TABLE natis_zapisnika (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_srecanje    bigint NOT NULL REFERENCES srecanje (id) ON DELETE CASCADE,
    oblika         text NOT NULL CHECK (oblika IN ('VRSTICE', 'KADER')),
    razlicica      integer NOT NULL CHECK (razlicica > 0),
    format         text NOT NULL,
    st_nizov       integer NOT NULL CHECK (st_nizov BETWEEN 1 AND 9),
    kader_domaci   text NOT NULL,
    kader_gost     text NOT NULL,
    id_ustvaril    bigint REFERENCES uporabnik (id) ON DELETE SET NULL,
    ustvarjeno_ob  timestamp(3) NOT NULL
);
CREATE INDEX idx_natis_zapisnika_srecanje ON natis_zapisnika (id_srecanje);

CREATE TABLE branje_zapisnika (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_nalozil          bigint REFERENCES uporabnik (id) ON DELETE SET NULL,
    id_natis            bigint REFERENCES natis_zapisnika (id) ON DELETE SET NULL,
    id_srecanje         bigint REFERENCES srecanje (id) ON DELETE SET NULL,
    stanje              text NOT NULL
                        CHECK (stanje IN ('V_VRSTI', 'PREBRANO', 'NAPAKA', 'ZAPISANO', 'ZAVRZENO')),
    samodejno           boolean NOT NULL,
    zapisano_samodejno  boolean NOT NULL DEFAULT false,
    zanesljivo          boolean,
    prebrano            text,
    celice              text,
    potrjeno            text,
    popravljeno         boolean,
    napaka              text,
    opomba              text,
    model               text,
    kljuc_posiljanja    text,
    ustvarjeno_ob       timestamp(3) NOT NULL,
    prebrano_ob         timestamp(3),
    zakljuceno_ob       timestamp(3),
    slika_izbrisana_ob  timestamp(3)
);
CREATE INDEX idx_branje_zapisnika_nalozil ON branje_zapisnika (id_nalozil, ustvarjeno_ob);
CREATE INDEX idx_branje_zapisnika_srecanje ON branje_zapisnika (id_srecanje);
CREATE UNIQUE INDEX uq_branje_zapisnika_kljuc ON branje_zapisnika (id_nalozil, kljuc_posiljanja)
    WHERE kljuc_posiljanja IS NOT NULL;

CREATE TABLE branje_zapisnika_slika (
    id_branje  bigint PRIMARY KEY REFERENCES branje_zapisnika (id) ON DELETE CASCADE,
    vsebina    bytea NOT NULL,
    sirina     integer NOT NULL CHECK (sirina > 0),
    visina     integer NOT NULL CHECK (visina > 0),
    poravnana  bytea
);

ALTER TABLE stevka_listka
    ADD COLUMN id_branje_zapisnika bigint REFERENCES branje_zapisnika (id) ON DELETE SET NULL;
ALTER TABLE stevka_listka DROP CONSTRAINT stevka_listka_en_vir;
ALTER TABLE stevka_listka
    ADD CONSTRAINT stevka_listka_en_vir CHECK (num_nonnulls(id_branje, id_vadnica, id_branje_zapisnika) <= 1);
CREATE INDEX idx_stevka_listka_zapisnik ON stevka_listka (id_branje_zapisnika)
    WHERE id_branje_zapisnika IS NOT NULL;
