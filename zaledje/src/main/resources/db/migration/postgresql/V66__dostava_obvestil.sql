-- ============================================================================
-- Turnirko: dostava obvestil po kolu in po turnirju po prejemnikih (V66, nov 2026)
-- Samo PostgreSQL (mapa sqlite/ je zamrznjena).
--
-- Doslej je bilo kolo (obvestilo_kola) oziroma turnir (obvestilo_turnirja)
-- zapisano kot obdelano v isti transakciji, v kateri je posta sele cakala na
-- potrditev. Ce posiljanje potem ni uspelo (streznik poste, zavrnjen naslov,
-- polna vrsta), se kolo ni poslalo nikoli vec.
--
-- Ta tabela belezi dostavo VSAKEMU prejemniku posebej. Vrstica nastane ob
-- prvem poskusu dostave:
--   poslano_ob   cas, ko je streznik poste sporocilo sprejel (NULL = se ne)
--   poskusov     stevilo poskusov, ki jih je streznik zavrnil ali sprejel;
--                izpad streznika (ni povezave) se ne steje
-- Kolo oziroma turnir se zapise kot obdelan sele, ko nihce vec ne caka
-- (poslano ali izcrpani poskusi). Enolicnost (kolo/turnir, racun) je varovalo
-- pred podvojeno posto istemu prejemniku.
--
-- Vrstica je ali za kolo lige (id_liga + kolo) ali za turnir (id_turnir).
-- ============================================================================

CREATE TABLE dostava_obvestila (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_liga           bigint REFERENCES liga (id) ON DELETE CASCADE,
    kolo              integer,
    id_turnir         bigint REFERENCES turnir (id) ON DELETE CASCADE,
    id_racun          bigint NOT NULL REFERENCES uporabnik (id) ON DELETE CASCADE,
    poslano_ob        timestamp(3),
    poskusov          integer NOT NULL DEFAULT 0,
    zadnji_poskus_ob  timestamp(3) NOT NULL,
    CHECK ((id_liga IS NOT NULL AND kolo IS NOT NULL AND id_turnir IS NULL)
        OR (id_liga IS NULL AND kolo IS NULL AND id_turnir IS NOT NULL))
);
CREATE UNIQUE INDEX idx_dostava_obvestila_kolo
    ON dostava_obvestila (id_liga, kolo, id_racun) WHERE id_liga IS NOT NULL;
CREATE UNIQUE INDEX idx_dostava_obvestila_turnir
    ON dostava_obvestila (id_turnir, id_racun) WHERE id_turnir IS NOT NULL;
CREATE INDEX idx_dostava_obvestila_racun ON dostava_obvestila (id_racun);
